use std::{
    fs::{File, create_dir_all, write},
    io::{Result, Write},
    path::PathBuf,
    process::Command,
};

use serde::Deserialize;
use serde_json::from_str;

#[derive(Debug, Deserialize, Clone)]
pub struct Targets {
    #[serde(rename = "GOOS")]
    pub goos: String,
    #[serde(rename = "GOARCH")]
    pub goarch: String,
    #[serde(rename = "CgoSupported")]
    pub cgosupported: bool,
    #[serde(rename = "FirstClass")]
    pub firstclass: bool,
}

pub fn get_targets() -> Result<Vec<Targets>> {
    let out = Command::new("go")
        .args(["tool", "dist", "list", "-json"])
        .output()?;

    let out_str = String::from_utf8_lossy(&out.stdout);

    let targets: Vec<Targets> = from_str(&out_str)?;

    Ok(targets)
}

pub fn make_dir(appname: &String, bin: bool) -> Result<()> {
    let project_dir = PathBuf::from(".").join(appname);

    let (src_dir, file_name, contents) = if bin {
        (
            project_dir.clone(),
            "main.go",
            "package main\n\nfunc main() {\n\n}".to_string(),
        )
    } else {
        (
            project_dir.join("pkg").join("lib"),
            "lib.go",
            format!("package {}\n", appname),
        )
    };

    create_dir_all(&src_dir)?;

    write(src_dir.join(file_name), contents)?;

    let _ = Command::new("go")
        .args(["mod", "init", appname])
        .current_dir(project_dir)
        .status()?;
    Ok(())
}

pub fn gen_template(
    goos: String,
    goarch: String,
    cgosupported: bool,
    firstclass: bool,
) -> Result<()> {
    let mut cgo = "CGO Support: No";
    let mut fclass = "First Class: No";

    if cgosupported {
        cgo = "CGO Support: Yes";
    }
    if firstclass {
        fclass = "First Class: Yes";
    }

    let template = format!(
        r#"# Generated by gotarget
# Template for {goos}/{goarch}
# {cgo}
# {fclass}

[build.release]
cmd = "go"
args = ["build", "-ldflags", "-s -w", "-trimpath", "-o", "myapp"]

[build.release.envs]
CGO_ENABLED = "0"
GOOS = "{goos}"
GOARCH = "{goarch}"
"#
    );
    let filename = format!("gotarget_{goos}_{goarch}.toml");
    let mut f = File::create_new(filename)?;
    f.write_all(template.as_bytes())?;

    Ok(())
}
